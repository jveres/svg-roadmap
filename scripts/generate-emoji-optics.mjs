// Regenerates src/core/emoji/artwork-optics.ts: the optical ink-center of
// every core-pack emoji, measured with a real SVG engine (headless Chrome).
// Badges use these to center artwork on their disc — many glyphs (the rocket,
// for example) carry asymmetric ink inside their viewBox. Centers are
// alpha-weighted pixel centroids, which track perceived mass better than
// bounding boxes for diagonal or lopsided glyphs.
//
//   node scripts/generate-emoji-optics.mjs
//
// Requires Google Chrome at the default macOS path or via CHROME env.
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const chrome = process.env.CHROME ?? "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome";

const artworkSource = new URL("../src/core/emoji/artwork-core.ts", import.meta.url);
const opticsTarget = new URL("../src/core/emoji/artwork-optics.ts", import.meta.url);

// The generated module is mechanical TS; strip the types to evaluate it.
const source = readFileSync(artworkSource, "utf8");
const body = source
	.replace(/^import[^\n]*\n/gmu, "")
	.replace("export const coreEmojiArtwork: Readonly<Record<string, EmojiArtwork>> =", "return")
	.replace(/;\s*$/u, "");
// eslint-disable-next-line no-new-func
const artwork = new Function(body)();

const page = `<!DOCTYPE html><html><body><div id="out"></div><script>
const artwork = ${JSON.stringify(artwork)};
async function measure() {
	const canvas = document.createElement("canvas");
	canvas.width = 128;
	canvas.height = 128;
	const context = canvas.getContext("2d", { willReadFrequently: true });
	const centers = {};
	for (const [name, art] of Object.entries(artwork)) {
		const svg = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="' + art.viewBox + '">' + art.content + "</svg>";
		const url = URL.createObjectURL(new Blob([svg], { type: "image/svg+xml" }));
		const image = new Image();
		await new Promise((resolve, reject) => {
			image.onload = resolve;
			image.onerror = reject;
			image.src = url;
		});
		context.clearRect(0, 0, 128, 128);
		context.drawImage(image, 0, 0, 128, 128);
		URL.revokeObjectURL(url);
		const pixels = context.getImageData(0, 0, 128, 128).data;
		let sumX = 0;
		let sumY = 0;
		let total = 0;
		for (let y = 0; y < 128; y += 1) {
			for (let x = 0; x < 128; x += 1) {
				const alpha = pixels[(y * 128 + x) * 4 + 3];
				if (alpha === 0) continue;
				sumX += x * alpha;
				sumY += y * alpha;
				total += alpha;
			}
		}
		if (total === 0) continue;
		const cx = sumX / total / 128;
		const cy = sumY / total / 128;
		if (Math.abs(cx - 0.5) > 0.008 || Math.abs(cy - 0.5) > 0.008) {
			centers[name] = [Math.round(cx * 1000) / 1000, Math.round(cy * 1000) / 1000];
		}
	}
	document.getElementById("out").textContent = JSON.stringify(centers);
}
measure();
</script></body></html>`;

const workDirectory = mkdtempSync(join(tmpdir(), "emoji-optics-"));
const pagePath = join(workDirectory, "optics.html");
writeFileSync(pagePath, page);
const dom = execFileSync(
	chrome,
	["--headless", "--dump-dom", "--virtual-time-budget=20000", `file://${pagePath}`],
	{ encoding: "utf8", maxBuffer: 64 * 1024 * 1024 },
);
rmSync(workDirectory, { recursive: true, force: true });

const match = dom.match(/<div id="out">([^<]*)<\/div>/u);
if (!match) throw new Error("Chrome did not produce the optics payload.");
const centers = JSON.parse(match[1].replaceAll("&quot;", '"').replaceAll("&amp;", "&"));

const entries = Object.entries(centers)
	.sort(([a], [b]) => a.localeCompare(b))
	.map(([name, [cx, cy]]) => `\t${JSON.stringify(name)}: [${cx}, ${cy}],`)
	.join("\n");

writeFileSync(
	opticsTarget,
	`// Generated by scripts/generate-emoji-optics.mjs — do not edit.
// Optical ink centers (as viewBox fractions) for core-pack artwork whose ink
// is not centered in its viewBox. Badges use these to center the glyph on
// their disc; anything absent is optically centered already.
export const emojiInkCenters: Readonly<Record<string, readonly [number, number]>> = {
${entries}
};
`,
);
console.log(`wrote ${Object.keys(centers).length} optical centers`);
